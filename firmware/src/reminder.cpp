// ==========================================================================
//  Internal config state
// ==========================================================================
static ReminderIntervalCfg _waterCfg  = { true,  120, 8, 22 };
static ReminderFoodCfg     _foodCfg   = { true,  8,0, 13,0, 19,0 };
static ReminderIntervalCfg _pillsCfg  = { false, 480, 8, 22 };

// Last-fired timestamps (millis) to prevent re-firing within cooldown
static unsigned long _lastFiredMs[REM_COUNT] = {0, 0, 0};
#define REMINDER_COOLDOWN_MS  60000u   // 1-minute cooldown after firing

// For food: which meal was last fired (0=breakfast,1=lunch,2=dinner), 0xFF=none
static uint8_t _lastFiredMeal = 0xFF;
// Track the day so we can reset meal-fired state at midnight
static uint8_t _lastFiredDay = 0xFF;

// ==========================================================================
//  NVS load / save
// ==========================================================================
static Preferences _remPrefs;
static bool _remPrefsReady = false;

void reminderLoadSettings() {
    _remPrefs.begin("qbitRem", false);
    _remPrefsReady = true;

    _waterCfg.enabled     = _remPrefs.getBool("wEn",   true);
    _waterCfg.intervalMin = _remPrefs.getUShort("wInt", 120);
    _waterCfg.startHour   = _remPrefs.getUChar("wSH",  8);
    _waterCfg.endHour     = _remPrefs.getUChar("wEH",  22);

    _foodCfg.enabled      = _remPrefs.getBool("fEn",   true);
    _foodCfg.breakfastH   = _remPrefs.getUChar("fBH",  8);
    _foodCfg.breakfastM   = _remPrefs.getUChar("fBM",  0);
    _foodCfg.lunchH       = _remPrefs.getUChar("fLH",  13);
    _foodCfg.lunchM       = _remPrefs.getUChar("fLM",  0);
    _foodCfg.dinnerH      = _remPrefs.getUChar("fDH",  19);
    _foodCfg.dinnerM      = _remPrefs.getUChar("fDM",  0);

    _pillsCfg.enabled     = _remPrefs.getBool("pEn",   false);
    _pillsCfg.intervalMin = _remPrefs.getUShort("pInt", 480);
    _pillsCfg.startHour   = _remPrefs.getUChar("pSH",  8);
    _pillsCfg.endHour     = _remPrefs.getUChar("pEH",  22);
}

void reminderSaveSettings() {
    if (!_remPrefsReady) return;

    _remPrefs.putBool("wEn",   _waterCfg.enabled);
    _remPrefs.putUShort("wInt", _waterCfg.intervalMin);
    _remPrefs.putUChar("wSH",  _waterCfg.startHour);
    _remPrefs.putUChar("wEH",  _waterCfg.endHour);

    _remPrefs.putBool("fEn",   _foodCfg.enabled);
    _remPrefs.putUChar("fBH",  _foodCfg.breakfastH);
    _remPrefs.putUChar("fBM",  _foodCfg.breakfastM);
    _remPrefs.putUChar("fLH",  _foodCfg.lunchH);
    _remPrefs.putUChar("fLM",  _foodCfg.lunchM);
    _remPrefs.putUChar("fDH",  _foodCfg.dinnerH);
    _remPrefs.putUChar("fDM",  _foodCfg.dinnerM);

    _remPrefs.putBool("pEn",   _pillsCfg.enabled);
    _remPrefs.putUShort("pInt", _pillsCfg.intervalMin);
    _remPrefs.putUChar("pSH",  _pillsCfg.startHour);
    _remPrefs.putUChar("pEH",  _pillsCfg.endHour);
}

// ==========================================================================
//  Enable / disable
// ==========================================================================
bool reminderGetEnabled(ReminderType type) {
    switch (type) {
        case REM_WATER: return _waterCfg.enabled;
        case REM_FOOD:  return _foodCfg.enabled;
        case REM_PILLS: return _pillsCfg.enabled;
        default: return false;
    }
}

void reminderSetEnabled(ReminderType type, bool enabled) {
    switch (type) {
        case REM_WATER: _waterCfg.enabled = enabled; break;
        case REM_FOOD:  _foodCfg.enabled  = enabled; break;
        case REM_PILLS: _pillsCfg.enabled = enabled; break;
        default: break;
    }
}

