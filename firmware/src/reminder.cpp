// ==========================================================================
//  Interval-based check helper (water / pills)
// ==========================================================================
static bool checkInterval(const ReminderIntervalCfg &cfg, uint8_t curH,
                          uint8_t curM, ReminderType type) {
    if (!cfg.enabled) return false;

    // Check hour window
    bool inWindow;
    if (cfg.startHour < cfg.endHour) {
        inWindow = (curH >= cfg.startHour && curH < cfg.endHour);
    } else {
        inWindow = (curH >= cfg.startHour || curH < cfg.endHour);
    }
    if (!inWindow) return false;

    // Check cooldown
    unsigned long now = millis();
    unsigned long cooldown = (unsigned long)cfg.intervalMin * 60000UL;
    if (_lastFiredMs[type] != 0 && (now - _lastFiredMs[type]) < cooldown)
        return false;

    // Check if current minute aligns with interval from start
    uint16_t minsSinceStart;
    if (curH >= cfg.startHour) {
        minsSinceStart = (uint16_t)(curH - cfg.startHour) * 60 + curM;
    } else {
        minsSinceStart = (uint16_t)(24 - cfg.startHour + curH) * 60 + curM;
    }
    return (minsSinceStart % cfg.intervalMin) == 0;
}

// ==========================================================================
//  Food check helper (fixed-time meals)
// ==========================================================================

// Meal labels by sub-index
static const char *_mealLabels[3] = { "Breakfast", "Lunch", "Dinner" };
static uint8_t _activeMealIdx = 0;  // which meal is being shown

static bool checkFood(uint8_t curH, uint8_t curM, uint8_t curDay) {
    if (!_foodCfg.enabled) return false;

    // Reset meal-fired tracking on new day
    if (curDay != _lastFiredDay) {
        _lastFiredMeal = 0xFF;
        _lastFiredDay = curDay;
    }

    // Cooldown
    unsigned long now = millis();
    if (_lastFiredMs[REM_FOOD] != 0 &&
        (now - _lastFiredMs[REM_FOOD]) < REMINDER_COOLDOWN_MS)
        return false;

    uint8_t mealH[3] = { _foodCfg.breakfastH, _foodCfg.lunchH, _foodCfg.dinnerH };
    uint8_t mealM[3] = { _foodCfg.breakfastM, _foodCfg.lunchM, _foodCfg.dinnerM };

    for (uint8_t i = 0; i < 3; i++) {
        if (curH == mealH[i] && curM == mealM[i]) {
            // Only fire once per meal per day
            if (_lastFiredMeal != 0xFF && i <= _lastFiredMeal) continue;
            _activeMealIdx = i;
            return true;
        }
    }
    return false;
}

// ==========================================================================
//  Public: check if any reminder should fire
// ==========================================================================
ReminderType reminderCheck() {
    if (!timeManagerSynced()) return REM_COUNT;

    time_t now = timeManagerNow();
    struct tm ti;
    localtime_r(&now, &ti);
    uint8_t h = (uint8_t)ti.tm_hour;
    uint8_t m = (uint8_t)ti.tm_min;
    uint8_t d = (uint8_t)ti.tm_mday;

    // Check water first, then food, then pills (priority order)
    if (checkInterval(_waterCfg, h, m, REM_WATER)) {
        _lastFiredMs[REM_WATER] = millis();
        return REM_WATER;
    }
    if (checkFood(h, m, d)) {
        _lastFiredMs[REM_FOOD] = millis();
        _lastFiredMeal = _activeMealIdx;
        return REM_FOOD;
    }
    if (checkInterval(_pillsCfg, h, m, REM_PILLS)) {
        _lastFiredMs[REM_PILLS] = millis();
        return REM_PILLS;
    }
    return REM_COUNT;
}

// ==========================================================================
//  Public: get label
// ==========================================================================
const char *reminderGetLabel(ReminderType type) {
    switch (type) {
        case REM_WATER: return "Drink Water";
        case REM_FOOD:  return _mealLabels[_activeMealIdx];
        case REM_PILLS: return "Take Medicine";
        default:        return "";
    }
}

// ==========================================================================
//  Public: draw reminder overlay (48x48 icon + text)
// ==========================================================================
void reminderDraw(ReminderType type) {
    u8g2.clearBuffer();

    // Draw 48x48 bitmap centered horizontally, top area
    const uint8_t *bmp = _bitmaps[type];
    int16_t bx = (128 - 48) / 2;
    u8g2.drawXBM(bx, 0, 48, 48, bmp);

    // Draw label below
    u8g2.setFont(u8g2_font_7x14B_tr);
    const char *label = reminderGetLabel(type);
    uint8_t lw = u8g2.getStrWidth(label);
    u8g2.drawStr((128 - lw) / 2, 62, label);

    rotateBuffer180();
    u8g2.sendBuffer();
}
